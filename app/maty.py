# -*- coding: utf-8 -*-
"""
РАСПОЗНАВАНИЕ НЕЦЕНЗУРНОЙ БРАНИ
===============================

Функция is_rude(текст) отвечает: есть ли в сообщении мат или грубые оскорбления.
Используется окном чата (okno.py).

Как устроено: ищутся корни нецензурных слов с учётом приставок и окончаний
(«нахуй», «заебал», «пиздец»…), а также простые попытки замаскировать слово
латинскими буквами («xуй», «блядь» с латинской «a» и т.п.).

Корни подобраны так, чтобы не срабатывать на обычные слова:
«употреблять», «учебный», «небо», «себя», «мандарин», «сукно», «хула», «худой» — не мат.

Если бот ошибается (пропускает мат или ругается на обычное слово) — список
шаблонов ниже можно дополнить. Проверка: .venv\\Scripts\\python.exe app\\maty.py
"""

import re

# Латинские буквы, похожие на русские («xуй», «бля» с латинскими буквами) → русские
LOOKALIKES = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у",
    "k": "к", "m": "м", "t": "т", "h": "н", "b": "в", "3": "з", "0": "о", "6": "б",
})

# Шаблоны (регулярные выражения). \b — граница слова.
PATTERNS = [
    r"\b(?:на|по|от|за|вы|до|ни|о|об|при|под|рас)?ху[йеяиюё]\w*",       # хуй, нахуй, похуй, хуёвый
    r"\w*пизд\w*",                                                     # пиздец, распиздяй
    r"\b(?:за|вы|на|у|от|по|пере|раз|разъ|съ|въ|до|о|при|под|об|недо)?ъ?[её]б(?!ург)(?:а|у|и|л|н|ш|ок|ец|ён|ыв|ат)\w*",
    r"\b\w*д[оа]лб[оа][её]б\w*",                                       # долбоёб
    r"\bбля(?:дь|ди|дский|дство|ть|ха|ха|ден)?\b|\bбляд\w*|\bблят\w*",  # бля, блядь, блять
    r"\bмуда[кч]\w*|\bмудил\w*|\bмудозвон\w*",
    r"\bзалуп\w*",
    r"\bсук[аиуе]\b|\bсучар\w*|\bсучк\w*",
    r"\bгандон\w*|\bпид[оа]р\w*|\bпидр\w*",
    r"\bманд[аыуе]\b|\bмандавош\w*",
    r"\bшлюх\w*",
    r"\b(?:иди|идите|пош[её]л|пошла|пошли|катись)\s+(?:ты\s+|вы\s+)?нах\b",   # «иди нах», «пошёл ты нах»
]
RUDE = re.compile("|".join(f"(?:{p})" for p in PATTERNS))


def normalize(text):
    """Нижний регистр, «ё» → «е», латинские двойники → русские буквы."""
    text = text.lower().replace("ё", "е")
    # Латиницу меняем только внутри слов, где есть и русские буквы, — чтобы не ломать ссылки
    def fix(match):
        word = match.group(0)
        return word.translate(LOOKALIKES) if re.search(r"[а-я]", word) or len(word) <= 6 else word
    return re.sub(r"[a-zа-я0-9]+", fix, text)


def is_rude(text):
    """True, если в тексте есть мат или грубое оскорбление."""
    if not text:
        return False
    return bool(RUDE.search(normalize(text)))


if __name__ == "__main__":
    # Самопроверка: что должно ловиться и что — нет
    rude = ["да пошёл ты нахуй", "Пиздец какой-то", "заебал уже", "бля, где касса",
            "Блядь", "ты сука", "долбоёб", "мудак", "xуй", "отъебись", "ебаный бот", "хуёвый концерт",
            "иди нах", "пошёл ты нах", "Пошли нах"]
    polite = ["Хочу употреблять меньше сахара", "учебный концерт", "Небо над филармонией",
              "купить для себя", "мандарины в буфете", "сукно на сцене", "худой скрипач",
              "Ебург далеко", "Хуан Диего Флорес", "оскорбление", "Хочу на Щелкунчика",
              "Пиковая дама", "Лебединое озеро", "Сколько стоит билет?", "мандат",
              "хочу похудеть", "500 рублей", "ребята, привет", "хребет", "сабля", "оскорблять",
              "употребляет", "Тебе понравится", "небольшой зал", "огребу", "Хуанита", "психология",
              "Ёлка для взрослых", "страхуй", "пошли на концерт", "иди на Нахимова", "Губернаторский оркестр", "Колибри", "хлеба", "Себастьян Бах",
              "https://iframeab-pre12510.intickets.ru/seance/73266066/#abiframe"]
    errors = [t for t in rude if not is_rude(t)] + [t for t in polite if is_rude(t)]
    for t in rude:
        print(("✔" if is_rude(t) else "✘ ПРОПУЩЕНО"), t)
    for t in polite:
        print(("✔" if not is_rude(t) else "✘ ЛОЖНОЕ СРАБАТЫВАНИЕ"), t)
    print("\nОшибок:", len(errors))
