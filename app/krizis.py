# -*- coding: utf-8 -*-
"""
РАСПОЗНАВАНИЕ ТРЕВОЖНЫХ СООБЩЕНИЙ
=================================

Функция crisis_kind(текст) отвечает, есть ли в сообщении:
  "себе"   — человеку очень плохо, он пишет о желании умереть или навредить себе;
  "угроза" — угроза другим людям или филармонии (взрыв, оружие, «заминировано»);
  ""       — ничего тревожного.

Используется окном чата (okno.py): на такие сообщения помощник отвечает заранее
написанным текстом с телефонами помощи — не через модель, чтобы ответ был всегда бережным.

Шаблоны можно дополнять. Проверка: .venv\\Scripts\\python.exe app\\krizis.py
"""

import re

SELF_HARM = [
    r"покончу с собой|покончить с собой|кончу с собой",
    r"убью себя|убить себя|убиться",
    r"суицид|самоубий",
    r"не хочу (больше )?жить|жить (больше )?не хочу|не хочется жить|жить не хочется",
    r"хочу умереть|хочется умереть|лучше бы я умер|лучше умереть|хочу сдохнуть|сдохнуть хочу",
    r"нет смысла жить|незачем жить|нет сил жить",
    r"повешусь|повеситься|вскрою вены|вскрыть вены|наложить на себя руки|наложу на себя руки",
    r"выпрыгну (из|с)|спрыгну (из|с) (окна|крыши|балкона|моста)|брошусь под",
    r"св(ести|еду) сч[её]ты с жизнью",
]

THREAT = [
    r"взорв(у|ём|ем|ать)\b|подорв(у|ём|ем)\b",
    r"заминир\w*|заложу бомбу|заложил(и)? бомбу|бомба в",
    r"теракт|террорист(ическ)?(ий|ая|ое)? акт",
    r"расстреляю|перестреляю|устрою стрельбу|приду с (оружием|ножом|пистолетом|ружь[её]м|автоматом)",
    r"убью (вас|тебя|всех|его|е[её]|кассир|охранник|директор)|всех убью|поубиваю|зарежу",
    r"подожгу|спалю (вашу|филармони|зал|здание)",
]

SELF_HARM_RE = re.compile("|".join(f"(?:{p})" for p in SELF_HARM))
THREAT_RE = re.compile("|".join(f"(?:{p})" for p in THREAT))


def crisis_kind(text):
    """'себе', 'угроза' или '' — см. описание в начале файла."""
    if not text:
        return ""
    t = " ".join(text.lower().replace("ё", "е").split())
    if SELF_HARM_RE.search(t.replace("ё", "е")):
        return "себе"
    if THREAT_RE.search(t):
        return "угроза"
    return ""


if __name__ == "__main__":
    tests = {
        "себе": ["Я больше не хочу жить", "хочу умереть, всё надоело", "Покончу с собой сегодня",
                 "жить не хочется", "думаю о суициде", "Лучше бы я умерла", "повешусь, бля",
                 "спрыгну с крыши"],
        "угроза": ["Я взорву вашу филармонию", "Филармония заминирована", "приду с ножом на концерт",
                   "всех убью", "в зале бомба в сумке, бомба в зале", "устрою теракт"],
        "": ["Хочу на Щелкунчика", "Спектакль про убийство в Восточном экспрессе есть?",
             "убил время в очереди", "Взрывной концерт был!", "Пиковая дама — там Германн умирает?",
             "мне жить не на что, есть скидки?", "Убийственно красивый голос", "Ромео и Джульетта",
             "Сколько стоит билет?", "подорожник", "Огонь концерт, зал взорвался аплодисментами"],
    }
    errors = 0
    for kind, texts in tests.items():
        for t in texts:
            got = crisis_kind(t)
            ok = got == kind
            errors += not ok
            print(("✔" if ok else f"✘ получилось «{got}», нужно «{kind}»"), t)
    print("\nОшибок:", errors)
